                <div class="title-desc">
                  <h2 class="display-4 display-title mb-4 anim-1">The dates did not move</h2>
                  <p class="anim-2">Sesame's bet was simple to explain and harder to make usable: shop for care the way you shop for anything else. See the price before you commit. Find an appointment. Pay upfront. No insurance in the middle. Providers could sell time that would otherwise go unused.</p>
                  <p class="anim-2">The dates did not move. We needed a working prototype for the J.P. Morgan Healthcare Conference on 7 Jan 2019 and a Kansas City beta shortly afterward. Sesame was fewer than 10 people, working from a Brooklyn Heights WeWork. There was no dedicated researcher or recruiting panel.</p>
                  <p class="anim-2"><strong>Guessing looked more expensive than talking to people.</strong></p>
                </div>
              </div>
            </div>
