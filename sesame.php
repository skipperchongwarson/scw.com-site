                <div class="anim-2">
                  <h2 class="display-4 display-title">Impact</h2>
                  <p class="anim-2"><strong>The dates held.</strong> We had a working prototype for JPM in January 2019 and launched the Kansas City beta afterward. By the time I left in August, the marketplace included approximately 500 providers.</p>
