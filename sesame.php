<script>
  (function () {
  const railLinks = document.querySelectorAll('.responsive-dot-rail a');

  railLinks.forEach(function (link) {
  link.addEventListener('click', function (event) {
  if (!document.body.classList.contains('fp-responsive')) return;

  event.preventDefault();
  event.stopPropagation();

  const sectionName = getSectionName(link);

  if (sectionName === 'top') {
  window.scrollTo(0, 0);
  setActiveRailLink('top');
  window.history.replaceState(null, '', '#top');
  return;
  }

  const target = document.querySelector(
  '.section[data-section="' + sectionName + '"]'
  );

  if (!target) return;

  target.scrollIntoView({
  behavior: 'smooth',
  block: 'start'
  });

  setActiveRailLink(sectionName);
  window.history.replaceState(null, '', '#' + sectionName);
  });
  });

  const sections = document.querySelectorAll('.section[data-section]');
  if (!sections.length) return;

  function getSectionName(link) {
  return link.getAttribute('href').split('#').pop();
  }

  function setActiveRailLink(sectionName) {
  railLinks.forEach(function (link) {
  link.classList.toggle(
  'is-active',
  getSectionName(link) === sectionName
  );
  });
  }

  const observer = new IntersectionObserver(
  function (entries) {
  entries.forEach(function (entry) {
  if (!entry.isIntersecting) return;
  setActiveRailLink(entry.target.getAttribute('data-section'));
  });
  },
  {
  rootMargin: '-45% 0px -45% 0px',
  threshold: 0
  }
  );

  sections.forEach(function (section) {
  observer.observe(section);
  });

  setActiveRailLink(sections[0].getAttribute('data-section'));
  })();
</script>
