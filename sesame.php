          <!-- RESEARCH AT LAUNCH SPEED -->
          <div class="row mt-5">
            <div class="col-12 col-md-9 text-left center-v">
              <div class="wrapper">
                <div class="title-desc">
                  <h2 class="display-4 display-title mb-4 anim-1">Research became part of shipping</h2>
                  <p class="anim-2">Every other Friday, we went downstairs with three $20 Amazon gift cards and recruited three people for roughly 40 minutes each. On Thursday we looked at the open questions. By Friday morning we cut them to five to seven. What we carried changed with the question: competitive screens, paper sketches, sticky notes, or a Figma prototype.</p>
                  <p class="anim-2">Anyone on the team could observe: founders, product, engineering, contractors, our copywriter. One person interviewed. No pitching, no demos.</p>
                </div>
                <div class="case-study-loop anim-2" aria-label="Research and iteration loop">
                  <span>Open questions</span><b>→</b>
                  <span>3 conversations</span><b>→</b>
                  <span>Shared observation</span><b>→</b>
                  <span>Change requirement</span><b>→</b>
                  <span>Design + build</span><b>→</b>
                  <span>Test again</span>
                </div>
                <div class="title-desc">
                  <p class="anim-2">That mattered because the people making the product heard the same thing at the same time. One Friday, a near-term booking interaction was incomprehensible to the participants. A co-founder, our head of product, and I were already in the room. We changed the requirement that afternoon, redesigned it, and had a new version coded and back in testing within days.</p>
                  <p class="anim-2">Across the pre-launch period I conducted <strong>21 interviews for about $400 in incentives.</strong></p>
                  <div class="case-study-note">
                    <p class="anim-2"><strong>The sample was imperfect.</strong> We were talking to tech workers in Brooklyn who were more likely to have insurance than the cash-pay customers we expected in Kansas City. I used that audience to test usability. Willingness to pay still needed better evidence. If I were screening it today, I would add one more question: have you ever paid for a medical visit entirely in cash?</p>
