                  <h3 class="anim-2 mt-5">A missing shopping basket</h3>
                  <p class="anim-2">After the Kansas City beta, Hotjar recordings showed another pattern. People would get close to checkout, move around the upper-left area of the page as if they were looking for something, and then the recording would end.</p>
                  <p class="anim-2">The recording showed us <em>where</em> the problem happened. We used roughly 9–11 UserTesting.com sessions to understand why and watched the same behavior again. Our hypothesis was that people wanted to review what they were buying before committing.</p>
                  <p class="anim-2">We introduced a shopping basket that kept the appointment context visible through checkout. <strong>Cart abandonment had been roughly 90%. After the basket launched, it fell to below 50%.</strong></p>
