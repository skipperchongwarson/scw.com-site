                  <h2 class="display-4 display-title mb-4 anim-1">From sketches to beta</h2>
                  <p class="anim-2">The marketplace was selling perishable inventory: appointment times. People needed to understand <em>when</em> they could actually get care and what to do when today did not work.</p>
                  <p class="anim-2">We explored ways to expose availability directly in search results. The version we landed on showed <strong>three dates first — today and the next two days</strong> — with appointment times grouped underneath and a control to move farther ahead. On mobile, the same model compressed into a small date strip; on desktop it expanded alongside provider details and the map.</p>
                  <p class="anim-2">The beta also had to work on the supply side. We tested provider-facing prototypes with a physician advisory council and worked through services, locations, staff, pricing, booked time, and the availability providers wanted to sell.</p>
