                  <h2 class="display-4 display-title mb-4 anim-1">Start with what matters now</h2>
                  <p class="anim-2">The Feed became the front door to the experience. Rather than asking someone to choose a legacy product first, it brought a small number of relevant items together from across the underlying research products: research reports, market commentary, upcoming events, new issues, and rating changes. From there, people could decide what deserved more attention and move into the source material or another part of their workflow.</p>

                  <figure class="case-study-figure">
                    <img src="/img/items/BOA-investors-feed.png" loading="lazy" decoding="async" alt="Bank of America research app Feed and detailed report-card anatomy">
                    <figcaption>The Feed mixed several content types in one personalized stream instead of reproducing the boundaries between the three source products.</figcaption>
                  </figure>

                  <h2 class="display-4 display-title mt-5 mb-4 anim-1">Make dense reports easier to use</h2>
                  <p class="anim-2">Research reports were the hard case. They were dense, but clients did not always need to read them from beginning to end. We designed ways to scan the important parts, move among chapters, search within a report, isolate charts, highlight passages, save material, and share it into another workflow.</p>
                  <p class="anim-2">I worked directly on the Feed and report experience shown here, as well as the flows, interface, prototype, and shared system connecting them.</p>

