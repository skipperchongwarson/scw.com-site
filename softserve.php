                  <h2 class="display-4 display-title mb-4 anim-1">Most clients were in the Americas but very few designers were</h2>
                  <p class="anim-2">The global design group had 160+ people. Four were in the U.S.; the rest were primarily in Ukraine, Bulgaria, and Poland. And meanwhile, 84% of the company’s clients were in the Americas.</p>
                  <p class="anim-2">That imbalance became harder to sustain as the client roster grew and demand for design and engineering increased. SoftServe also wanted access to a large technology talent pool closer to North American clients and with less time-zone separation than its European teams.</p>
                  <p class="anim-2">So the company began expanding delivery capacity into Latin America, including Guadalajara, Medellín, and Chile. Russia’s invasion of Ukraine in 2022 did not create that strategy, but it accelerated the need to diversify where delivery teams were based.</p>

