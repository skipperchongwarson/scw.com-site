                <h2 class="display-4 display-title mb-4 anim-1">And the team delivered</h2>
                  <p class="anim-2">Over two years, we were able to maintain 80%+ utilization, generated $2.1M in billable work, and staffed about 15 projects, usually with one designer and occasionally 2–3.</p>
                  <p class="anim-2">The regional capacity reduced reliance on European teams for work in the Americas and gave colleagues better coverage across the working day. At least one teammate was promoted and everyone was still on the team when I left.</p>
                  <p class="anim-2">Those results mattered because it showed that the organization was not simply adding headcount. The team was being staffed, retained, and used productively.</p>
                  <p class="anim-2">Shortly before I left, several direct reports also reached out to thank me for the time and energy I'd put into team building efforts and group bonding, which meant so much to me.</p>
