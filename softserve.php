                <div class="title-desc">
                  <h2 class="display-4 display-title mt-5 mb-4 anim-1">Having the team closer to the work could help (but it wouldn't be enough)</h2>
                  <p class="anim-2">The first hypothesis was straightforward: put more design capacity closer to the clients we were serving.</p>
                  <p class="anim-2">As the team grew across the U.S., Canada, Mexico, Colombia, and Chile, a second problem became obvious. Geography could improve coverage across the working day, but it did not automatically create trust, communication, or a shared way of working.</p>
                  <p class="anim-2">Because the team was fully remote and spread across five countries, we needed a way to connect. Erin Meyer’s <i>The Culture Map</i> was a useful starting point for understanding some of the cultural differences in communication, what feedback worked well, and ways to deepen trust.</p>
                  <p class="anim-2">Early on, we used lightweight activities such as PechaKucha presentations, 10-song mixtapes, and family/pet intros to help people know one another beyond project work.</p>
                  <p class="anim-2">As the team approached a dozen people, I expected our meetings would become more tactical with occasional drops into what was happening outside the camera frame. But the team gave us a better signal: they wanted less project reporting in weekly calls and more time to connect and sink in with each other.</p>
                  <p class="anim-2">So we moved the status reporting out of the meeting. If we were going to get 12 people across five countries on a call, we might as well use the time for something Slack couldn’t do.</p>
