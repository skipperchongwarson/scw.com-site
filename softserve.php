                  <h2 class="display-4 display-title mb-4 anim-1">Build the team, then change how we worked</h2>
                  <p class="anim-2">I worked with country leaders as well as global design and cross-functional leadership on where to hire and how to staff the new capacity.</p>
                  <p class="anim-2">SoftServe already had a rigorous hiring process covering communication and follow-through, portfolio quality, collaboration, problem-solving, and interview performance. But when helpful, we involved the broader team and brought Spanish-speaking colleagues into later-round interviews so candidates had more ways to show how they worked. We even started an internship class with a group of five student designers.</p>
                  <p class="anim-2">At the same time, we shifted our own cadences and rhythms. Routine project updates moved to a twice-monthly Teams post. Weekly calls shifted away from status reporting and toward conversations, activities, book clubs, games, baking, and other ways of spending time together. And leadership of those meetings was handed off across the team.</p>
                  <p class="anim-2">My role expanded with the organization, the management piece was there too: headcount plan, seven hires, 12 people across five countries, two managers, staffing, utilization, performance, careers. All of it.</p>

