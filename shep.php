                  <h2 class="display-4 display-title mb-4 anim-1">Enterprise pilots, then COVID-19</h2>
                  <p class="anim-2">Flight Centre invested at the end of 2019. Adidas, Discovery Channel, and other companies became enterprise pilots.</p>
				 
                  <p class="anim-2">The pilots were meant to prove that Shep could turn off-channel bookings into visible trips. The extension needed to detect the booking, put company guidance in front of the employee, and give travel and safety teams enough information to respond when a trip went sideways.</p>
                  <p class="anim-2">Then COVID-19 collapsed business travel and froze the pilots. The same product experience now had to carry fast-changing health and safety guidance in the context of a trip.</p>
				  
