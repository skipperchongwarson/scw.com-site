                <div class="title-desc">
                  <h2 class="display-4 display-title mb-4 anim-1">When travel went off channel, companies lost sight of the traveler</h2>
                  <p class="anim-2">In 2017, about 30% of business travel was booked outside company travel systems (according to <a href="https://www.phocuswire.com/business-travel-part-4-data-management-for-leakage" 
   aria-label="PhocusWire article on business travel leakage and data management">PhocusWire</a>). An employee could book on a consumer site, and the trip might never enter the company’s travel records.</p>
                  <p class="anim-2">Then something would go wrong: a cancellation, new vaccination requirements, or a new regulation. The company was still responsible for the traveler, but might not know where they were, what guidance they had seen, or how to reach them.</p>
                  <p class="anim-2">That breakdown touched four groups:</p>
                  <ul class="content-list anim-2">
                    <li>Employees wanted to use familiar booking sites</li>
                    <li>Travel managers needed off-channel trips and policy exceptions to be visible</li>
                    <li>Executives responsible for duty of care needed to find and support people during disruptions</li>
                    <li>HR teams needed a reliable way to communicate with employees in transit</li>
                  </ul>
                  <p class="anim-2">Small and medium businesses seemed like the obvious first market. But after a year, the economics didn’t hold. Travel volume was inconsistent, budgets were thin, and customer acquisition cost too much.</p>
                </div>
                <!-- title and description -->
                <div class="title-desc">
                  <h2 class="display-4 display-title mt-5 mb-4 anim-1">Meet travelers where they already book</h2>
                  <p class="anim-2">Enterprise changed the stakes. If a traveler disappeared from the system, the company was still responsible for them.</p>
                  <p class="anim-2">Shep could meet employees on the consumer sites they already used. The browser extension could detect an off-channel booking, show policy and health guidance at the point of booking, and give travel and duty-of-care teams enough trip data to find and support the traveler later.</p>
				  
