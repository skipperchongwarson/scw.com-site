                <div class="title-desc">
                  <h2 class="display-4 display-title mb-4 anim-1">Where should a small team focus?</h2>
                  <p class="anim-2">The working name for their product was nut.new, it was a fork of Bolt that gave the AI suite access to real runtime data: what the app was doing, what had broken, and why.</p>
                  <p class="anim-2">In spring 2025, AI tools could generate a working prototype quickly, but would often stall when a change failed. The AI couldn't see what was happening behind the scenes while nut.new could inspect the runtime, debug the problem, run tests, and push a fix through.</p>
                  <p class="anim-2">Replay's CEO and a small engineering team had a hunch about who needed it most. The decision left was where to focus: who to recruit, which problem had enough teeth, and how to position the product.</p>
                </div>

                <!-- Insight / hypothesis -->
                <div class="title-desc">
                  <h2 class="display-4 display-title mt-5 mb-4 anim-1">The first hypothesis</h2>
                  <p class="anim-2">The first bet was that operations managers needed help automating simple create, read, update, and delete (CRUD) workflows. We framed the hypothesis together, recruited five people, designed the interview guide, and away we went.</p>
                  <p class="anim-2">In those interviews, they all described real problems:</p>
                  <ul class="content-list anim-2">
                    <li>Setup paralysis</li>
                    <li>Fragmented tools</li>
                    <li>The fear of breaking something they could not repair</li>
                  </ul>
                  <p class="anim-2">But across the five interviews, there didn't seem much pressure to change. One operations manager put it plainly: “I’d rather deal with the inefficiency I know than risk configuring something wrong.”</p>
                </div>
              </div>
            </div>
