                  <h2 class="display-4 display-title mb-4 anim-1">Decisions changed</h2>
				  <p class="anim-2">Across our work together, I could see the Bullseye Customer work inform four types of decisions — </p>
                  <ul class="content-list anim-2">
                    <li><strong>Customer:</strong> Operations managers dropped out of focus after the first interviews showed real pain with little pressure to change</li>
					<li><strong>Recruiting:</strong> We rewrote the criteria after each cycle as the customer definition got narrower, mostly using <a href="https://www.userinterviews.com" aria-label="User Interviews participant recruitment and screening platform">userinterviews.com</a> for screening and qualification</li>
					<li><strong>Audience:</strong> Replay moved from a broad app-builder audience toward non-technical creators who had already shipped something real</li>
					<li><strong>Positioning:</strong> The problem moved toward continuation: helping someone understand and fix what broke after they had already built and shipped</li>
                  </ul>
				  <p class="anim-2">Replay’s community manager and developer relations lead put it this way:</p>
				  <blockquote class="editorial-blockquote">
				    <p>“There are moments when you feel like you've built the right product, but you're not sure you're reaching the right people, and that's where Skipper really shines. He has a talent for cutting through the noise, helping teams clearly define their target audience and identify their bullseye customer.”</p>
				    <cite>— Filip, community manager and DevRel lead at Replay</cite>
				  </blockquote>
				  
				  <h2 class="display-4 display-title mt-5 mb-4 anim-1">What Replay has shipped</h2>
				  <p class="anim-2">nut.new launched in spring 2025. Replay Builder followed in Dec 2025, Replay QA in May 2026, and MCP integrations with Claude Code and Codex in Jun 2026.</p>
				  <p class="anim-2">Those launches belong to Replay’s continuing product work. I don't claim them as follow-on effects of my work — customer definition, recruiting criteria, and positioning decisions — but they address the same continuation problems the interviews surfaced.</p>
