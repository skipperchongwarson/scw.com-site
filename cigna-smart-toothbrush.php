                <div class="title-desc">
                  <h2 class="display-4 display-title mb-4 anim-1">First, prove there was a signal worth designing around</h2>
                  <p class="anim-2">Cigna had investigated connected dental care before, so another speculative concept wasn't what the team needed. We began with a Clear Path Forward workshop and ecosystem mapping exercise, then interviewed 10 stakeholders, seven prospective customers, five dental professionals, and a benefits buyer. The goal was to understand where a connected service could be useful, where it would add friction, and what questions had to be answered before Cigna invested further.</p>
                  <p class="anim-2">In parallel, engineering analyzed a number of leading smart toothbrushes and recreated their data exchange with custom firmware. We narrowed it down to six. The brushes didn't all expose the same information, but the team was able to receive usable data from supported devices. Depending on the model, that included signals such as session duration, pressure, coverage, and brush state.</p>
                  <p class="anim-2">We did not wire the toothbrush hardware, data processing, and complete application into a production-like end-to-end system. That wasn't the question this proof of concept needed to answer. We needed to know whether the connection worked and what information we could reliably design around.</p>
                  <p class="anim-2">That distinction mattered. Once the signal was real, we could stop designing around an imagined smart toothbrush and start designing around what the devices could actually tell us.</p>
                  <p class="anim-2">The product direction followed from there: use brushing data to coach people in the moment, then reinforce healthier routines over time through challenges, progress, badges, points, and Cigna rewards. Rewards could give people a reason to come back. The coaching had to make coming back worthwhile.</p>

