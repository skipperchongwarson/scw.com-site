                  <h2 class="display-4 display-title mb-4 anim-1">Turn the signal into feedback people could use</h2>
                  <p class="anim-2">The experience began with pairing a compatible toothbrush, then put the brushing session at the center. Members could see duration, pressure, and coverage while they brushed, review their activity over time, and receive practical guidance based on their own data.</p>
                  <p class="anim-2">The important shift was from measurement to meaning. Knowing that someone brushed for a certain number of seconds wasn't especially useful by itself. Showing where they had missed, whether they were applying too much pressure, or how their routine was changing over time gave the data a job.</p>
                  <p class="anim-2">Family profiles came directly from the research. Parents wanted to build healthier habits with their children, even when their own routines slipped. That also meant a child's experience couldn't simply be a smaller version of the adult one. We explored ways to make brushing feel more playful through challenges, progress, badges, and rewards, while giving parents a clearer view of habits across the household.</p>
                  <p class="anim-2">A conversational coach extended the experience beyond an individual brushing session with education, encouragement, and a path back to dental care when needed.</p>

