                <div class="title-desc">
                  <h2 class="display-4 display-title mb-4 anim-1">Between dental visits, the habit was mostly on its own</h2>
                  <p class="anim-2">The dentists and front-desk staff we spoke with were already juggling patient context, benefit information, and material from multiple vendors. There was little room for sustained coaching between appointments—especially when many patients weren't visiting on a predictable six-month schedule to begin with.</p>
                  <p class="anim-2">Outside of those appointments, the people we interviewed had rarely been coached on how they brushed or flossed. Parents wanted to model good habits for their children, but struggled to maintain those routines themselves. About half of the prospective customers we spoke with were Cigna members, so the research intentionally reached beyond Cigna's existing member base.</p>
                  <p class="anim-2">The broader data showed a similar gap between intention and behavior. A 2015 ADA study found that 77% of adults planned to visit a dentist within the next year, while only 37% had done so in the previous year.</p>
                  <p class="anim-2">That suggested the opportunity was bigger than improving a single brushing session. What happened between appointments mattered, and for most people there was no one there to observe the habit, offer feedback, or help make it better.</p>
                  <p class="anim-2">Our hypothesis was that Cigna could use a connected toothbrush—either one a member already owned or one provided through the program—to make prevention more tangible between visits.</p>
                  <p class="anim-2">The model was already familiar in healthcare. Activity trackers and smartwatches didn't just count movement; they gave people feedback and helped turn an invisible behavior into something they could see and understand. Could a toothbrush do something similar for oral health?</p>
                  <p class="anim-2">Before designing too far ahead, we needed to know whether there was actually a useful signal to work with.</p>
