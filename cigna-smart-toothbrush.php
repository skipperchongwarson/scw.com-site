                  <h3 class="anim-2 mt-5">What I led</h3>
                  <p class="anim-2">My role was to keep research, design, product, and engineering pointed at the same questions while moving the team from ambiguity toward decisions. I stayed hands-on across:</p>
                  <ul class="content-list anim-2">
                    <li>Framing the eight-week engagement around the questions Cigna needed answered before deciding on a next phase</li>
                    <li>Workshop facilitation, research, synthesis, and product direction</li>
                    <li>Connecting device capabilities and constraints to product and experience decisions</li>
                    <li>Experience design and design-system direction</li>
                    <li>Leading the design team while working closely with product and engineering</li>
                    <li>Client communication and alignment throughout the engagement</li>
                  </ul>
                  <p class="anim-2">The remote team included two designers, a project manager, and seven other product and technology specialists. Together, we produced the proof of concept, application architecture, MVP backlog, gamification model, and a phased roadmap for what testing, development, and launch could look like next.</p>
