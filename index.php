<script>
(function () {
	const sectionLinks = document.querySelectorAll(
		'a[href$="#home"], a[href$="#about"], a[href$="#select-projects"], a[href$="#contact"]'
	);

	const railLinks = document.querySelectorAll(
		'.responsive-dot-rail a'
	);

	const sidebarItems = document.querySelectorAll(
		'#qmenu [data-menuanchor]'
	);

	const sections = document.querySelectorAll(
		'.section[data-section]'
	);

	if (!sections.length) return;

	function getSectionName(link) {
		return link.getAttribute('href').split('#').pop();
	}

	function activateDot(sectionName) {
		railLinks.forEach(function (link) {
			link.classList.toggle(
				'is-active',
				getSectionName(link) === sectionName
			);
		});

		sidebarItems.forEach(function (item) {
			item.classList.toggle(
				'active',
				item.getAttribute('data-menuanchor') === sectionName
			);
		});
	}

	let isNavigating = false;
	let navigatingTo = null;
	let navigationEndTimer;

	function finishNavigation() {
		if (!isNavigating) return;

		isNavigating = false;

		if (navigatingTo) {
			activateDot(navigatingTo);
		}

		navigatingTo = null;
	}

	sectionLinks.forEach(function (link) {
		link.addEventListener('click', function (event) {
			if (!document.body.classList.contains('fp-responsive')) {
				return;
			}

			const sectionName = getSectionName(link);
			const target = document.querySelector(
				'.section[data-section="' + sectionName + '"]'
			);

			if (!target) return;

			event.preventDefault();

			isNavigating = true;
			navigatingTo = sectionName;

			activateDot(sectionName);

			target.scrollIntoView({
				behavior: 'smooth',
				block: 'start'
			});

			window.history.replaceState(
				null,
				'',
				'#' + sectionName
			);

			clearTimeout(navigationEndTimer);

			navigationEndTimer = window.setTimeout(
				finishNavigation,
				1200
			);
		});
	});

	const observer = new IntersectionObserver(
		function (entries) {
			if (isNavigating) return;

			const visible = entries
				.filter(function (entry) {
					return entry.isIntersecting;
				})
				.sort(function (a, b) {
					return b.intersectionRatio - a.intersectionRatio;
				});

			if (visible.length) {
				activateDot(
					visible[0].target.getAttribute('data-section')
				);
			}
		},
		{
			root: null,
			rootMargin: '-35% 0px -35% 0px',
			threshold: [0, 0.25, 0.5, 0.75]
		}
	);

	sections.forEach(function (section) {
		observer.observe(section);
	});

	window.addEventListener('scroll', function () {
		if (isNavigating) {
			clearTimeout(navigationEndTimer);

			navigationEndTimer = window.setTimeout(
				finishNavigation,
				140
			);

			return;
		}

		const nearBottom =
			window.innerHeight + window.scrollY >=
			document.documentElement.scrollHeight - 24;

		if (nearBottom) {
			activateDot('contact');
		}
	}, { passive: true });

	activateDot('home');
})();
</script>

